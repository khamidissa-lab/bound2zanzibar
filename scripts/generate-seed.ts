/**
 * Generates supabase/seed.sql from the sample data layer (src/data/sample),
 * so the website's sample content and the development database never drift.
 *
 *   npm run db:seed:generate
 *
 * DEVELOPMENT ONLY. Every content row is flagged is_sample = true and every
 * price is_illustrative = true. Never load this seed into production.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { contact, socialLinks } from "../src/config/site";
import { sampleArticles } from "../src/data/sample/articles";
import { sampleCategories } from "../src/data/sample/categories";
import { sampleDestinations } from "../src/data/sample/destinations";
import { samplePackages } from "../src/data/sample/packages";
import { sampleTours } from "../src/data/sample/tours";
import type { PriceRecord } from "../src/types/content";

const q = (value: string | null | undefined): string =>
  value === null || value === undefined ? "null" : `'${value.replace(/'/g, "''")}'`;

const arr = (values: string[]): string =>
  values.length === 0 ? "'{}'::text[]" : `array[${values.map(q).join(", ")}]::text[]`;

const json = (value: unknown): string => `${q(JSON.stringify(value))}::jsonb`;

const paragraphs = (values: string[]): string => q(values.join("\n\n"));

const lines: string[] = [];
const out = (sql: string) => lines.push(sql);

out(`-- =============================================================================
-- DEVELOPMENT SEED — generated by scripts/generate-seed.ts. Do not edit by hand.
-- Sample content and ILLUSTRATIVE prices for local development and review only.
-- Never load into production.
-- =============================================================================

begin;
`);

out("-- Tour categories");
sampleCategories.forEach((c, i) => {
  out(
    `insert into public.tour_categories (name, slug, description, sort_order) values (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${i});`,
  );
});

out("\n-- Destinations");
sampleDestinations.forEach((d, i) => {
  out(`insert into public.destinations
  (name, slug, region, short_description, description, highlights, cover_image_alt,
   is_featured, status, seo_title, seo_description, is_sample, sort_order)
values (${q(d.name)}, ${q(d.slug)}, ${q(d.region)}, ${q(d.summary)}, ${paragraphs(d.description)},
  ${arr(d.highlights)}, ${q(d.coverImage.alt)}, ${d.featured}, ${q(d.status)},
  ${q(d.seo.title)}, ${q(d.seo.description)}, ${d.isSample}, ${i});`);
});

const priceRows = (prices: PriceRecord[]) =>
  prices.flatMap((p) => [
    { ...p, customerType: "adult", amount: p.adult },
    ...(p.child === null ? [] : [{ ...p, customerType: "child", amount: p.child }]),
  ]);

out("\n-- Tours");
sampleTours.forEach((t, i) => {
  out(`insert into public.tours
  (category_id, destination_id, name, slug, short_description, description, duration_text,
   length, travel_styles, highlights, inclusions, exclusions, what_to_bring, meeting_point, difficulty, suitability,
   what_to_expect, good_to_know, faqs,
   cover_image_alt, is_featured, status, seo_title, seo_description, is_sample, sort_order)
values (
  (select id from public.tour_categories where slug = ${q(t.categorySlug)}),
  (select id from public.destinations where slug = ${q(t.destinationSlug)}),
  ${q(t.name)}, ${q(t.slug)}, ${q(t.shortDescription)}, ${paragraphs(t.description)}, ${q(t.duration)},
  ${q(t.length)}, ${arr(t.travelStyles)}, ${arr(t.highlights)}, ${arr(t.included)}, ${arr(t.excluded)}, ${arr(t.whatToBring)},
  ${q(t.meetingPoint)}, ${q(t.difficulty)}, ${q(t.suitability)},
  ${json(t.whatToExpect)}, ${arr(t.goodToKnow)}, ${json(t.faqs)}, ${q(t.coverImage.alt)},
  ${t.featured}, ${q(t.status)}, ${q(t.seo.title)}, ${q(t.seo.description)}, ${t.isSample}, ${i});`);
  for (const p of priceRows(t.prices)) {
    out(`insert into public.tour_prices (tour_id, market, customer_type, currency, amount, unit_label, is_illustrative)
values ((select id from public.tours where slug = ${q(t.slug)}), ${q(p.market)}, ${q(p.customerType)}, ${q(p.currency)}, ${p.amount}, ${q(p.unit)}, ${p.isIllustrative});`);
  }
});

out("\n-- Packages");
samplePackages.forEach((p, i) => {
  out(`insert into public.packages
  (name, slug, short_description, description, days, nights, accommodation_description,
   transfers_description, meals_description, inclusions, exclusions, terms, is_safari, travel_styles,
   is_featured, cover_image_alt, status, seo_title, seo_description, is_sample, sort_order)
values (${q(p.name)}, ${q(p.slug)}, ${q(p.summary)}, ${paragraphs(p.description)}, ${p.days}, ${p.nights},
  ${q(p.accommodation)}, ${q(p.transfers)}, ${q(p.meals)}, ${arr(p.included)}, ${arr(p.excluded)},
  ${arr(p.terms)}, ${p.isSafari}, ${arr(p.travelStyles)}, ${p.featured}, ${q(p.coverImage.alt)}, ${q(p.status)},
  ${q(p.seo.title)}, ${q(p.seo.description)}, ${p.isSample}, ${i});`);
  const pkgId = `(select id from public.packages where slug = ${q(p.slug)})`;
  p.destinationSlugs.forEach((slug, order) => {
    out(`insert into public.package_destinations (package_id, destination_id, sort_order)
values (${pkgId}, (select id from public.destinations where slug = ${q(slug)}), ${order});`);
  });
  for (const tourSlug of p.includedTourSlugs) {
    out(`insert into public.package_tours (package_id, tour_id)
values (${pkgId}, (select id from public.tours where slug = ${q(tourSlug)}));`);
  }
  for (const day of p.itinerary) {
    out(`insert into public.package_itinerary_days (package_id, day_number, title, description, meals, overnight)
values (${pkgId}, ${day.day}, ${q(day.title)}, ${q(day.description)}, ${arr(day.meals)}, ${q(day.overnight)});`);
  }
  for (const price of priceRows(p.prices)) {
    out(`insert into public.package_prices (package_id, market, customer_type, currency, amount, unit_label, is_illustrative)
values (${pkgId}, ${q(price.market)}, ${q(price.customerType)}, ${q(price.currency)}, ${price.amount}, ${q(price.unit)}, ${price.isIllustrative});`);
  }
});

out("\n-- Travel guide articles");
for (const a of sampleArticles) {
  out(`insert into public.blog_posts
  (title, slug, excerpt, body, tags, reading_minutes, cover_image_alt, status, published_at,
   seo_title, seo_description, is_sample)
values (${q(a.title)}, ${q(a.slug)}, ${q(a.excerpt)}, ${json(a.sections)}, ${arr(a.tags)},
  ${a.readingMinutes}, ${q(a.coverImage.alt)}, ${q(a.status)}, ${q(a.publishedOn)}::timestamptz,
  ${q(a.seo.title)}, ${q(a.seo.description)}, ${a.isSample});`);
}

out("\n-- Public site settings (owner-supplied contact details)");
const settings: [string, unknown, string][] = [
  ["contact.email", contact.email, "Public contact email"],
  ["contact.phone", contact.phone, "Public phone number (E.164)"],
  ["contact.address", null, "Office address — awaiting owner"],
  [
    "social.links",
    socialLinks.map(({ label, handle, href }) => ({ label, handle, href })),
    "Social profiles",
  ],
  ["pricing.default_market", "international", "Market shown before a visitor chooses"],
];
for (const [key, value, description] of settings) {
  out(
    `insert into public.site_settings (key, value, is_public, description) values (${q(key)}, ${json(value)}, true, ${q(description)});`,
  );
}

out("\ncommit;\n");

const target = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${target}`);
